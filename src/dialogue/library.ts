export function speechOptions(species: Species, personality: PersonalityId = 'shy', event: SpeechEvent): readonly string[] {
  const bank = species === 'cat' ? CAT_SPEECH : DOG_SPEECH
  return (bank[personality] ?? bank.shy)[event]
}
// Inject random in tests. Avoid an immediate repeat without touching saved game state.
export function selectSpeech(species: Species, personality: PersonalityId | undefined, event: SpeechEvent, previous = '', random: () => number = Math.random): string {
  const choices = speechOptions(species, personality, event)
  const fresh = choices.filter(line => line !== previous)
  const available = fresh.length ? fresh : choices
  const sample = random()
  const index = Number.isFinite(sample) ? Math.max(0, Math.min(available.length - 1, Math.floor(sample * available.length))) : 0
  return available[index]
}
